function descriptor(): ShotDescriptor {
  const base = {
    levelId: REGULATION_LEVEL.id,
    shooterX: params.shooterX,
    releaseY: params.releaseY,
    angleDeg: params.angleDeg,
    speed: params.speed,
    // Spin is not user-controllable in v1 (DESIGN.md §1); it is still carried through the core and
    // is still generated by contact friction.
    omega: 0,
    flags: { drag: params.drag, magnus: params.magnus },
  };
  return Object.keys(overrides).length > 0
    ? makeDescriptor({ ...base, materialOverrides: overrides })
    : makeDescriptor(base);
}

function logParam(param: string, from: number, to: number): void {
  if (from === to || !logger.enabled('info')) return;
  logger.emit({ t: sim.t, tick: sim.tick, level: 'info', cat: 'input', kind: 'param_change', param, from, to });
}

function rebuildGhost(): void {
  ghost = view.ghost ? tracePath(world, descriptor(), { every: 3 }) : [];
}

/** Material changes alter the World, so it is rebuilt rather than mutated (DESIGN.md §5.6). */
function rebuildWorld(): void {
  world = buildWorld(REGULATION_LEVEL, Object.keys(overrides).length > 0 ? overrides : undefined);
  const wasFlight = sim.phase === 'flight';
  const keep = cloneBall(sim.ball);
  sim = new Simulation(world, logger);
  if (wasFlight) {
    // Mid-flight material edits restart the shot rather than splicing worlds, which would make the
    // run unreproducible from its descriptor.
    sim.release(descriptor());
  } else {
    sim.idle(params.shooterX, params.releaseY);
    sim.ball = keep;
  }
  rebuildGhost();
}

function reset(): void {
  sim.idle(params.shooterX, params.releaseY);
  trail = [];
  contactMarks = [];
  prevBall = cloneBall(sim.ball);
  hud.showResult(null);
  rebuildGhost();
}

function release(): void {
  if (sim.phase === 'flight') return;
  trail = [];
  contactMarks = [];
  sim.release(descriptor());
  prevBall = cloneBall(sim.ball);
  writeHash();
}

// ---------------------------------------------------------------------------------------------
// URL hash: a shot is shareable because it is reproducible (DESIGN.md §4.1, §8)
// ---------------------------------------------------------------------------------------------

function writeHash(): void {
  const p = new URLSearchParams({
    x: params.shooterX.toFixed(3),
    y: params.releaseY.toFixed(3),
    a: params.angleDeg.toFixed(2),
    s: params.speed.toFixed(3),
  });
  if (params.drag) p.set('drag', '1');
  if (params.magnus) p.set('magnus', '1');
  history.replaceState(null, '', `#${p.toString()}`);
}

function readHash(): void {
  if (location.hash.length < 2) return;
  const p = new URLSearchParams(location.hash.slice(1));
  const num = (key: string, lo: number, hi: number, cur: number): number => {
    const raw = p.get(key);
    if (raw === null) return cur;
    const n = Number(raw);
    return Number.isFinite(n) ? clamp(n, lo, hi) : cur;
  };
  params.shooterX = num('x', SHOOTER_X_MIN, SHOOTER_X_MAX, params.shooterX);
  params.releaseY = num('y', RELEASE_Y_MIN, RELEASE_Y_MAX, params.releaseY);
  params.angleDeg = num('a', 0, 89, params.angleDeg);
  params.speed = num('s', 0, MAX_SPEED, params.speed);
  params.drag = p.get('drag') === '1';
  params.magnus = p.get('magnus') === '1';
}

readHash();

