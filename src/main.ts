/** Cap on steps per frame, so a slow frame cannot spiral into an ever-growing backlog. */
const MAX_STEPS_PER_FRAME = 40;

let cssW = 0;
let cssH = 0;

function resize(): void {
  const dpr = window.devicePixelRatio || 1;
  const rect = canvasWrap.getBoundingClientRect();
  cssW = Math.max(rect.width, 320);
  cssH = Math.max(rect.height, 240);
  canvas.width = Math.round(cssW * dpr);
  canvas.height = Math.round(cssH * dpr);
  canvas.style.width = `${cssW}px`;
  canvas.style.height = `${cssH}px`;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
}

function currentCamera() {
  return fitCamera(cssW, cssH);
}

function lerp(a: Vec2, b: Vec2, f: number): Vec2 {
  return v2(a.x + (b.x - a.x) * f, a.y + (b.y - a.y) * f);
}

let lastFrame = 0;
let acc = 0;
let lastResultShown: object | null = null;

function frame(now: number): void {
  const dtReal = lastFrame === 0 ? 0 : Math.min((now - lastFrame) / 1000, 0.25);
  lastFrame = now;

  if (!paused && sim.phase === 'flight') {
    acc += dtReal * timeScale;
    let steps = 0;
    while (acc >= DT && steps < MAX_STEPS_PER_FRAME) {
      prevBall = cloneBall(sim.ball);
      sim.step();
      acc -= DT;
      steps++;
      if (view.trail && trail.length < 4000) trail.push(sim.ball.p);
      if (sim.phase !== 'flight') {
        acc = 0;
        break;
      }
    }
  }

  // The log panel follows the logger on its own (see createLogPanel), so the frame loop only has
  // to deal with the verdict.
  if (sim.result !== null && sim.result !== lastResultShown) {
    lastResultShown = sim.result;
    hud.showResult(sim.result.summary);
  }

  draw();
  requestAnimationFrame(frame);
}

function draw(): void {
  const cam = currentCamera();
  drawBackground(ctx, cssW, cssH);
  drawCourt(ctx, cam, world);
  drawFreeThrowLine(ctx, cam, FT_LINE_X);
  drawGoal(ctx, cam, world);

  if (view.colliders) drawColliders(ctx, cam, world);
  if (view.ghost && sim.phase !== 'flight') drawGhost(ctx, cam, ghost);
  if (view.trail) drawTrail(ctx, cam, trail);
  if (view.contacts) drawContacts(ctx, cam, contactMarks, sim.t);

  drawShooter(ctx, cam, params.shooterX, params.releaseY);

  // Interpolate between the last two sim states so motion is smooth at any refresh rate.
  const alpha = sim.phase === 'flight' ? clamp(acc / DT, 0, 1) : 1;
  const shown = { ...sim.ball, p: lerp(prevBall.p, sim.ball.p, alpha) };
  drawBall(ctx, cam, shown);

  if (view.velocity) drawVelocity(ctx, cam, shown);
  if (sim.phase !== 'flight') {
    drawAim(ctx, cam, v2(params.shooterX, params.releaseY), params.angleDeg, params.speed, MAX_SPEED);
  }

  // Scale bar, so the court reads as a real-world space.
  ctx.fillStyle = COLORS.text;
  ctx.font = '12px ui-monospace, monospace';
  ctx.textAlign = 'left';
  ctx.fillText(`${(1).toFixed(0)} m = ${cam.px(1).toFixed(0)} px`, 12, cssH - 12);
}

