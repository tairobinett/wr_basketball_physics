function setAngle(deg: number): void {
  const v = clamp(deg, 0, 89);
  logParam('angleDeg', params.angleDeg, v);
  params.angleDeg = v;
  sliderAngle.set(v);
}

function setSpeed(mps: number): void {
  const v = clamp(mps, 0, MAX_SPEED);
  logParam('speed', params.speed, v);
  params.speed = v;
  sliderPower.set((v / MAX_SPEED) * 100);
  speedReadout.textContent = `${v.toFixed(2)} m/s`;
}

function nudge(key: string, shift: boolean): boolean {
  // Shift gives fine control: a tenth of a degree, or 0.01 m/s. The make window is only about
  // 0.14 m/s wide, so coarse steps skip straight over it.
  const angleStep = shift ? 0.1 : 1;
  const speedStep = shift ? 0.01 : 0.1;

  switch (key) {
    case 'ArrowUp':
      setAngle(params.angleDeg + angleStep);
      break;
    case 'ArrowDown':
      setAngle(params.angleDeg - angleStep);
      break;
    case 'ArrowRight':
      setSpeed(params.speed + speedStep);
      break;
    case 'ArrowLeft':
      setSpeed(params.speed - speedStep);
      break;
    default:
      return false;
  }
  rebuildGhost();
  writeHash();
  return true;
}

window.addEventListener('keydown', (e) => {
  const target = e.target as HTMLElement | null;
  if (target !== null && /^(INPUT|SELECT|TEXTAREA)$/.test(target.tagName)) return;

  if (nudge(e.key, e.shiftKey)) {
    e.preventDefault();
    return;
  }

  switch (e.key) {
    case ' ':
      e.preventDefault();
      release();
      break;
    case 'r':
    case 'R':
      reset();
      break;
    case 'p':
    case 'P':
      paused = !paused;
      pauseBtn.textContent = paused ? 'Resume  (P)' : 'Pause  (P)';
      break;
    case '.':
      sim.step();
      break;
    case 'g':
    case 'G':
      view.ghost = !view.ghost;
      toggleGhost.set(view.ghost);
      rebuildGhost();
      break;
    case 'c':
    case 'C':
      view.colliders = !view.colliders;
      toggleColliders.set(view.colliders);
      break;
    case '?':
      help.classList.toggle('hidden');
      break;
    case 'Escape':
      help.classList.add('hidden');
      break;
    default:
      break;
  }
});

// Drag from the shooter: direction sets the angle, distance sets the power.
canvas.addEventListener('pointerdown', (e) => {
  const cam = currentCamera();
  const p = cam.toWorld(e.offsetX, e.offsetY);
  if (dist(p, v2(params.shooterX, params.releaseY)) < 0.75) {
    dragging = true;
    canvas.setPointerCapture(e.pointerId);
  }
});

canvas.addEventListener('pointermove', (e) => {
  if (!dragging) return;
  const cam = currentCamera();
  const p = cam.toWorld(e.offsetX, e.offsetY);
  const from = v2(params.shooterX, params.releaseY);
  const dx = p.x - from.x;
  const dy = p.y - from.y;
  if (dx === 0 && dy === 0) return;

  const angle = clamp((Math.atan2(dy, dx) * 180) / Math.PI, 0, 89);
  // 3 m of drag is full power, which feels about right at the default zoom.
  const speed = clamp((len(v2(dx, dy)) / 3) * MAX_SPEED, 0, MAX_SPEED);

  params.angleDeg = angle;
  params.speed = speed;
  sliderAngle.set(angle);
  sliderPower.set((speed / MAX_SPEED) * 100);
  speedReadout.textContent = `${speed.toFixed(2)} m/s`;
  rebuildGhost();
});

canvas.addEventListener('pointerup', (e) => {
  if (!dragging) return;
  dragging = false;
  canvas.releasePointerCapture(e.pointerId);
  writeHash();
  release();
});

